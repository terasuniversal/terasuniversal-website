-- Run as the container superuser. Objects are created by the non-superuser role `migrator`
-- (BYPASSRLS, like Supabase's `postgres`), so ownership/ACL behaviour matches Production.

do $$ begin
  if not exists (select 1 from pg_roles where rolname='migrator') then create role migrator nologin bypassrls; end if;
  if not exists (select 1 from pg_roles where rolname='anon') then create role anon nologin; end if;
  if not exists (select 1 from pg_roles where rolname='authenticated') then create role authenticated nologin; end if;
  if not exists (select 1 from pg_roles where rolname='service_role') then create role service_role nologin bypassrls; end if;
  if not exists (select 1 from pg_roles where rolname='outsider') then create role outsider nologin; end if;
end $$;
grant anon, authenticated, service_role, outsider, migrator to postgres;

create schema extensions;
create extension pgcrypto schema extensions;
grant usage on schema extensions to public;
do $$ begin execute format('alter database %I set search_path = "$user", public, extensions', current_database()); end $$;
do $$ begin execute format('grant create on database %I to migrator', current_database()); end $$;
create schema auth authorization migrator;
create schema app authorization migrator;
grant usage on schema auth, app to anon, authenticated, service_role, outsider;
grant all on schema public to migrator;
grant usage on schema public to anon, authenticated, service_role, outsider;

set role migrator;
set search_path = public, extensions;

-- Same contract as Supabase: uid comes from the request JWT claim setting.
create function auth.uid() returns uuid language sql stable as
$$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;

