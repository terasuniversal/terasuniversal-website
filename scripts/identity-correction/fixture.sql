-- ---- Production function bodies (read from the live project) ---------------------------------
create function app.current_role() returns public.user_role language sql stable security definer set search_path to 'public' as
$$ select role from public.profiles where id = (select auth.uid()); $$;
create function app.is_active() returns boolean language sql stable security definer set search_path to 'public' as
$$ select coalesce((select is_active from public.profiles where id = (select auth.uid())), false); $$;
create function app.has_min_role(min_role public.user_role) returns boolean language sql stable security definer set search_path to 'public' as
$$ select app.is_active() and array_position(enum_range(null::public.user_role), app.current_role())
    <= array_position(enum_range(null::public.user_role), min_role); $$;
create function app.is_admin() returns boolean language sql stable security definer set search_path to 'public' as
$$ select app.has_min_role('admin'::public.user_role); $$;
create function app.is_super_admin() returns boolean language sql stable security definer set search_path to 'public' as
$$ select app.current_role() = 'super_admin' and app.is_active(); $$;
create function app.log_event(p_action public.audit_action, p_entity_type text default null, p_entity_id text default null,
  p_summary text default null, p_metadata jsonb default '{}'::jsonb) returns void language plpgsql security definer set search_path to 'public' as
$$ declare v_email text; begin
  select email into v_email from public.profiles where id = auth.uid();
  insert into public.audit_logs (actor_id, actor_email, action, entity_type, entity_id, summary, metadata)
  values (auth.uid(), v_email, p_action, p_entity_type, p_entity_id, p_summary, coalesce(p_metadata, '{}'::jsonb));
end; $$;
create function public.set_updated_at() returns trigger language plpgsql set search_path to '' as
$$ begin new.updated_at = now(); return new; end; $$;
create function app.set_updated_at() returns trigger language plpgsql as
$$ begin new.updated_at = now(); return new; end; $$;
create function app.audit_trigger() returns trigger language plpgsql security definer set search_path to 'public' as
$$ declare v_action public.audit_action; v_id text; v_email text; begin
  select email into v_email from public.profiles where id = auth.uid();
  if tg_op = 'INSERT' then v_action := 'create'; v_id := coalesce(to_jsonb(new)->>'id', to_jsonb(new)->>'key');
  elsif tg_op = 'UPDATE' then
    if to_jsonb(new) ? 'deleted_at' and (to_jsonb(old)->>'deleted_at') is null and (to_jsonb(new)->>'deleted_at') is not null then v_action := 'delete';
    elsif to_jsonb(new) ? 'deleted_at' and (to_jsonb(old)->>'deleted_at') is not null and (to_jsonb(new)->>'deleted_at') is null then v_action := 'restore';
    else v_action := 'update'; end if;
    v_id := coalesce(to_jsonb(new)->>'id', to_jsonb(new)->>'key');
  else v_action := 'delete'; v_id := coalesce(to_jsonb(old)->>'id', to_jsonb(old)->>'key'); end if;
  insert into public.audit_logs (actor_id, actor_email, action, entity_type, entity_id, summary)
  values (auth.uid(), v_email, v_action, tg_table_name, v_id, tg_table_name || ' ' || v_action);
  if tg_op = 'DELETE' then return old; end if;
  return new;
end; $$;
create function app.certificates_before_insert() returns trigger language plpgsql as
$$ begin
  if new.certificate_number is null and new.certificate_no is not null then new.certificate_number := new.certificate_no; end if;
  if new.certificate_number is null or new.certificate_number = '' then
    new.certificate_number := 'CERT-' || to_char(coalesce(new.issue_date, current_date), 'YYYY') || '-' || lpad(nextval('public.certificate_number_seq')::text, 6, '0'); end if;
  if new.certificate_no is null then new.certificate_no := new.certificate_number; end if;
  if new.verification_token is null or new.verification_token = '' then new.verification_token := encode(gen_random_bytes(16), 'hex'); end if;
  if new.holder_name is null and new.participant_name is not null then new.holder_name := new.participant_name; end if;
  if new.participant_name is null and new.holder_name is not null then new.participant_name := new.holder_name; end if;
  return new;
end; $$;
create function public.sync_participant_last4() returns trigger language plpgsql set search_path to '' as
$$ declare cleaned text; begin
  if new.identity_no is not null and btrim(new.identity_no) <> '' then
    cleaned := regexp_replace(new.identity_no, '[^0-9A-Za-z]', '', 'g');
    if length(cleaned) >= 4 then new.identity_last4 := upper(right(cleaned, 4)); end if;
  elsif new.identity_last4 is not null then
    new.identity_last4 := upper(right(regexp_replace(new.identity_last4, '[^0-9A-Za-z]', '', 'g'), 4));
  end if;
  return new;
end; $$;
create function app.is_wah_course_label(p_label text) returns boolean language sql immutable set search_path to 'pg_catalog' as
$$ select coalesce(
    p_label ~* '(^|[^[:alnum:]])work(ing)?[[:space:]_-]*at[[:space:]_-]*heights?([^[:alnum:]]|$)'
    or p_label ~* '(^|[^[:alnum:]])wah([^[:alnum:]]|$)', false); $$;
create function app.is_wah_legacy_target(p_course_id uuid, p_course_name text) returns boolean language sql stable security definer set search_path to 'pg_catalog' as
$$ select coalesce(p_course_id = '963b1f6b-4c15-4833-90da-21aa0af0f544'::uuid, false)
    or app.is_wah_course_label(p_course_name)
    or exists (select 1 from public.courses co where co.id = p_course_id
        and (app.is_wah_course_label(co.title) or app.is_wah_course_label(co.course_name) or app.is_wah_course_label(co.course_code))); $$;
create function app.wah_participant_holds_certificate(p_participant_id uuid) returns boolean language sql stable security definer set search_path to 'pg_catalog' as
$$ with me as (
    select upper(regexp_replace(coalesce(p.identity_no, ''), '[^0-9A-Za-z]', '', 'g')) as identity_no,
           upper(regexp_replace(coalesce(p.ic_passport_no, ''), '[^0-9A-Za-z]', '', 'g')) as ic_passport_no
    from public.participants p where p.id = p_participant_id)
  select exists (
    select 1 from public.certificates c
    left join public.participants holder on holder.id = c.participant_id
    cross join lateral (values
      (upper(regexp_replace(coalesce(c.identity_no, ''), '[^0-9A-Za-z]', '', 'g'))),
      (upper(regexp_replace(coalesce(holder.identity_no, ''), '[^0-9A-Za-z]', '', 'g'))),
      (upper(regexp_replace(coalesce(holder.ic_passport_no, ''), '[^0-9A-Za-z]', '', 'g')))) as known(identity_value)
    where c.deleted_at is null and c.status <> 'revoked' and app.is_wah_legacy_target(c.course_id, c.course_name)
      and (c.participant_id = p_participant_id
           or (known.identity_value <> '' and exists (select 1 from me where known.identity_value in (me.identity_no, me.ic_passport_no))))); $$;

-- The CURRENT Production historical guard, verbatim.
create function app.certificate_historical_update_guard() returns trigger language plpgsql security definer
  set search_path to 'public', 'app', 'extensions' as
$function$
begin
  if exists (select 1 from public.certificate_issuance_snapshots s where s.certificate_id = old.id) then
    if new.certificate_no is distinct from old.certificate_no
      or new.participant_name is distinct from old.participant_name
      or new.identity_last4 is distinct from old.identity_last4
      or new.course_name is distinct from old.course_name
      or new.course_code is distinct from old.course_code
      or new.schedule_code is distinct from old.schedule_code
      or new.exam_date is distinct from old.exam_date
      or new.training_start_date is distinct from old.training_start_date
      or new.training_end_date is distinct from old.training_end_date
      or new.participant_id is distinct from old.participant_id
      or new.course_id is distinct from old.course_id
      or new.schedule_id is distinct from old.schedule_id
      or new.template_id is distinct from old.template_id
      or new.holder_name is distinct from old.holder_name
      or new.identity_no is distinct from old.identity_no
      or new.trainer_name is distinct from old.trainer_name
      or new.instructor is distinct from old.instructor
      or new.venue is distinct from old.venue
      or new.branch_id is distinct from old.branch_id
      or new.branch_code is distinct from old.branch_code
      or new.branch_name is distinct from old.branch_name
      or new.branch_address is distinct from old.branch_address
      or new.effective_assessor_name is distinct from old.effective_assessor_name
      or new.participant_code_snapshot is distinct from old.participant_code_snapshot
      or new.company_snapshot is distinct from old.company_snapshot
      or new.issue_date is distinct from old.issue_date
      or new.certificate_number is distinct from old.certificate_number
      or new.verification_token is distinct from old.verification_token
      or new.verification_url is distinct from old.verification_url
      or new.issued_by is distinct from old.issued_by
      or new.replaces_certificate_id is distinct from old.replaces_certificate_id
      or new.certificate_file_url is distinct from old.certificate_file_url
      or new.metadata is distinct from old.metadata
      or new.legacy_batch_id is distinct from old.legacy_batch_id
    then
      raise exception 'Modern certificate historical fields are immutable.' using errcode = '22000';
    end if;
  end if;
  return new;
end;
$function$;

