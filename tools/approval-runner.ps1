> Generated by ``tools/approval-runner.ps1``. Applies ONLY to the task below - not a standing or global permission. A new task always starts back at Human Decision: PENDING.

Task ID: $($State.TaskId)
Approved At: $(Get-Date -Format "yyyy-MM-dd HH:mm:ss")
Approved State: $Decision
$reasonLine

Approved Files:
$approvedFilesText

QA Summary: $qaSummary
Review Verdict: $($State.ReviewVerdict)

Commit Allowed: $(if ($Decision -eq "APPROVED" -or $Decision -eq "PREVIEW_APPROVED") { "YES (this task only, subject to -PrepareCommit/-Commit's own checks)" } else { "NO" })
Push Allowed: $(if ($Decision -eq "APPROVED" -or $Decision -eq "PREVIEW_APPROVED") { "YES (this task only, subject to -PreparePush's own eligibility/branch checks)" } else { "NO" })
Deploy Allowed: NO
Migration Apply Allowed: NO

Preview Approved: $(if ($State.PreviewApproved) { "YES" } else { "NO" })
Preview Approved At: $(if ($State.PreviewApprovedAt) { $State.PreviewApprovedAt } else { "(none)" })
Preview Commit SHA: $(if ($State.PreviewCommitSha) { $State.PreviewCommitSha } else { "(none)" })
Preview Deployment ID: $(if ($State.PreviewDeploymentIdApproved) { $State.PreviewDeploymentIdApproved } else { "(none)" })
Production Deployment Allowed: NO

Release Approved: $(if ($State.ReleaseApproved) { "YES" } else { "NO" })
Release Approved At: $(if ($State.ReleaseApprovedAt) { $State.ReleaseApprovedAt } else { "(none)" })
Approved PR: $(if ($State.ReleaseApprovedPr) { $State.ReleaseApprovedPr } else { "(none)" })
Approved Commit SHA: $(if ($State.ReleaseApprovedCommitSha) { $State.ReleaseApprovedCommitSha } else { "(none)" })
Approved Target Branch: $(if ($State.PrTargetBranch) { $State.PrTargetBranch } else { "(none)" })
