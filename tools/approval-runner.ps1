    }

    $state.State = "BLOCKED"
    $state.HumanDecision = "REJECTED"
    Save-TaskState -State $state
    Save-ApprovalRecord -State $state -Decision "REJECTED"

    Write-Host ""
    Write-Host "Task rejected."
    Write-Host ""
    Write-Host "No files were reverted."
    Write-Host "No commit created."
    Write-Host "No push performed."
    Write-Host "No deployment performed."
    Write-Host ""
    Write-Host "The human should decide what happens to the working tree."
    Write-Host ""
}

