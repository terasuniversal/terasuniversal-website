    $qaSummary = "Git Diff Check=$($State.QA.GitDiffCheck.Result), TypeScript=$($State.QA.TypeScript.Result), Tests=$($State.QA.Tests.Result), Build=$($State.QA.Build.Result)"
    $reasonLine = if ($Reason) { "Reason: $Reason" } else { "" }

    $content = @"
