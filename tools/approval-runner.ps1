function Invoke-PrepareCommit {
    $state = Get-TaskState
    if ($state.State -eq "NONE") {
        Write-Host ""
        Write-Host "No current task found."
        Write-Host ""
        return
    }

    if ($state.State -notin @("APPROVED", "COMMIT_READY")) {
        Write-Host ""
        Write-Host "PREPARE COMMIT BLOCKED"
        Write-Host ""
        Write-Host "Reason:"
        Write-Host "Task must be APPROVED first (current state: $($state.State))."
        Write-Host ""
        return
    }

    $message = Show-CommitPreview -State $state
    $state.CommitMessage = $message
    $state.State = "COMMIT_READY"
    Save-TaskState -State $state
}

function Get-StagedFiles {
    Push-Location $RepoRoot
    try {
        return @(git diff --cached --name-only)
    } finally {
        Pop-Location
    }
}

# Best-effort, not a substitute for real secret scanning - only exists to
# stop an anomalous report (one of our own generated .ai/*.md files, which
# should never contain a secret per BUSINESS_RULES.md/CLAUDE.md's logging
# rules) from being copied into the audit-trail snapshot unexamined.
function Test-SecretPattern {
    param([string]$Content)

    $patterns = @(
        'SUPABASE_SERVICE_ROLE_KEY',
        'service_role',
        'sk-[A-Za-z0-9]{10,}',
        'eyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}',
        'AKIA[0-9A-Z]{16}',
        '(?i)password\s*[:=]\s*\S+',
        'BEGIN (RSA|EC|OPENSSH) PRIVATE KEY',
        '-----BEGIN CERTIFICATE-----'
    )
    foreach ($p in $patterns) {
        if ($Content -match $p) { return $true }
    }
    return $false
}

function New-HistorySnapshot {
    param($State)

    $historyDir = Join-Path $AiDir "history\$($State.TaskId)"
    $reportFiles = @(
        "CURRENT_TASK.md", "IMPLEMENTATION_REPORT.md", "REVIEW_REPORT.md", "FINAL_REPORT.md", "APPROVAL.md",
        "PREVIEW_REPORT.md", "PR_REPORT.md", "RELEASE_REPORT.md", "ROLLBACK_PLAN.md"
    )

    foreach ($name in $reportFiles) {
        $src = Join-Path $AiDir $name
        if (Test-Path $src) {
            $content = Get-Content -Path $src -Raw
            if (Test-SecretPattern -Content $content) {
                Write-Host ""
                Write-Host "HISTORY SNAPSHOT BLOCKED"
                Write-Host ""
                Write-Host "Potential sensitive information detected in $name. Snapshot skipped;"
                Write-Host "the commit itself is not affected by this check."
                Write-Host ""
                return $false
            }
        }
    }

    New-Item -ItemType Directory -Path $historyDir -Force | Out-Null
    foreach ($name in $reportFiles) {
        $src = Join-Path $AiDir $name
        $dst = Join-Path $historyDir $name
        if (Test-Path $src) {
            Copy-Item -Path $src -Destination $dst -Force
        } else {
            Set-Content -Path $dst -Value "NOT_REQUIRED" -Encoding utf8
        }
    }
    Write-Host "History snapshot saved to .ai/history/$($State.TaskId)/"
    return $true
}

function Invoke-Commit {
    $state = Get-TaskState
    if ($state.State -eq "NONE") {
        Write-Host ""
        Write-Host "No current task found."
        Write-Host ""
        return
    }

    if ($state.State -notin @("APPROVED", "COMMIT_READY")) {
        Write-Host ""
        Write-Host "COMMIT BLOCKED"
        Write-Host ""
        Write-Host "Current state:"
        Write-Host $state.State
        Write-Host ""
        Write-Host "Required state:"
        Write-Host "APPROVED or COMMIT_READY"
        Write-Host ""
        return
    }

    $message = Show-CommitPreview -State $state
    $state.CommitMessage = $message

    $approvedFiles = @($state.TaskGeneratedFiles)
    if ($approvedFiles.Count -eq 0) {
        Write-Host "No task-generated files recorded. Nothing to commit."
        return
    }

    $preStaged = Get-StagedFiles
    if ($preStaged.Count -gt 0) {
        Write-Host ""
        Write-Host "PRE-EXISTING STAGED CHANGES DETECTED"
        Write-Host ""
        foreach ($f in $preStaged) { Write-Host "- $f" }
        Write-Host ""
        Write-Host "COMMIT BLOCKED"
        Write-Host "Human intervention required."
        Write-Host ""
        return
    }

    Push-Location $RepoRoot
    try {
        git add -- $approvedFiles

        Write-Host ""
        git diff --cached --stat
        Write-Host ""
        $checkOutput = git diff --cached --check 2>&1
        if ($LASTEXITCODE -ne 0) {
            Write-Host "git diff --cached --check reported issues:"
            Write-Host ($checkOutput -join "`n")
            Write-Host ""
            Write-Host "COMMIT BLOCKED"
            Write-Host "Resolve the issues above, then retry. Staged files were left as-is."
            Write-Host ""
            return
        }

        $stagedSet = @(Get-StagedFiles) | Sort-Object -Unique
        $approvedSet = $approvedFiles | Sort-Object -Unique
        $mismatch = Compare-Object -ReferenceObject $approvedSet -DifferenceObject $stagedSet
        if ($mismatch) {
            Write-Host ""
            Write-Host "COMMIT BLOCKED"
            Write-Host ""
            Write-Host "Staged scope does not match approved scope."
            Write-Host ""
            return
        }

        Write-Host ""
        Write-Host "========================================"
        Write-Host "FINAL COMMIT CONFIRMATION"
        Write-Host "========================================"
        Write-Host ""
        Write-Host "Task:"
        Write-Host $state.Description
        Write-Host ""
        Write-Host "Files:"
        Write-Host $approvedFiles.Count
        Write-Host ""
        foreach ($f in $approvedFiles) { Write-Host "- $f" }
        Write-Host ""
        Write-Host "Commit message:"
        Write-Host $message
        Write-Host ""
        Write-Host "QA:"
        Write-Host $(if (Test-QaHasBlockingFailure -QaResults $state.QA) { "FAIL" } else { "PASS" })
        Write-Host ""
        Write-Host "Independent Review:"
        Write-Host $state.ReviewVerdict
        Write-Host ""
        Write-Host "This action will create a local Git commit."
        Write-Host ""
        Write-Host "It will NOT:"
        Write-Host "- push"
        Write-Host "- deploy"
        Write-Host "- apply migrations"
        Write-Host "- modify production data"
        Write-Host ""

        $confirm = Read-Host "Type YES to create commit"
        if ($confirm -cne "YES") {
            Write-Host ""
            Write-Host "Commit cancelled. No commit was created."
            Write-Host "The approved files remain staged for your review; unstage manually if desired."
            Write-Host ""
            return
        }

        New-HistorySnapshot -State $state | Out-Null

        git commit -m $message
        if ($LASTEXITCODE -ne 0) {
            Write-Host ""
            Write-Host "git commit failed. Staged files were left as-is for inspection."
            Write-Host ""
            return
        }

        $sha = (git rev-parse HEAD).Trim()
        Write-Host ""
        git show --stat --oneline HEAD
        Write-Host ""
        git status --short
        Write-Host ""

        $state.CommitSha = $sha
        $state.State = "COMPLETE"
        Save-TaskState -State $state
        Save-ApprovalRecord -State $state -Decision "APPROVED"

        Write-Host "Commit Status: CREATED"
        Write-Host "Commit SHA: $sha"
        Write-Host "Commit Message: $message"
        Write-Host ""
        Write-Host "Local Engineering Task: COMPLETE"
        Write-Host "Production Deployment: NOT PERFORMED"
        Write-Host ""
    } finally {
        Pop-Location
    }
}

