    Set-Content -Path $path -Value $content -Encoding utf8
}

function Invoke-Approve {
    $state = Get-TaskState
    if ($state.State -eq "NONE") {
        Write-Host ""
        Write-Host "No current task found. Nothing to approve."
        Write-Host ""
        return
    }

    # Phase 4: once a task has reached PREVIEW_READY, -Approve records
    # approval of the PREVIEW (Invoke-ApprovePreview, preview-runner.ps1)
    # rather than re-approving the already-committed task.
    if ($state.State -eq "PREVIEW_READY") {
        Invoke-ApprovePreview -State $state
        return
    }

    if ($state.State -ne "AWAITING_APPROVAL") {
        Write-Host ""
        Write-Host "APPROVAL BLOCKED"
        Write-Host ""
        Write-Host "Reason:"
        Write-Host "Task is not awaiting approval (current state: $($state.State))."
        Write-Host ""
        return
    }

    if ($state.ScopeCheck -eq "FAIL") {
        Write-Host ""
        Write-Host "APPROVAL BLOCKED"
        Write-Host ""
        Write-Host "Reason:"
        Write-Host "Unauthorized file changes detected."
        Write-Host ""
        return
    }

    if ($state.ScopeCheck -eq "NOT_CONFIGURED") {
        Write-Host ""
        Write-Host "APPROVAL BLOCKED"
        Write-Host ""
        Write-Host "Reason:"
        Write-Host "Scope has not been verified for this task (Allowed Files was never configured)."
        Write-Host ""
        return
    }

    if (Test-QaHasBlockingFailure -QaResults $state.QA) {
        Write-Host ""
        Write-Host "APPROVAL BLOCKED"
        Write-Host ""
        Write-Host "Reason:"
        Write-Host "Blocking QA failure detected."
        Write-Host ""
        return
    }

    $reviewMandatory = ($state.Reviewer -eq "Codex" -or $state.Reviewer -eq "Human")
    if ($reviewMandatory -and $state.ReviewVerdict -notin @("PASS", "PASS_WITH_NOTES")) {
        Write-Host ""
        Write-Host "APPROVAL BLOCKED"
        Write-Host ""
        Write-Host "Reason:"
        Write-Host "Mandatory independent review has not completed."
        Write-Host ""
        return
    }

    $state.State = "APPROVED"
    $state.HumanDecision = "APPROVED"
    Save-TaskState -State $state
    Save-ApprovalRecord -State $state -Decision "APPROVED"

    Write-Host ""
    Write-Host "Task APPROVED."
    Write-Host "Commit Allowed: YES (this task only)  |  Push: NO  |  Deploy: NO  |  Migration Apply: NO"
    Write-Host "Next: teras-agent -PrepareCommit"
    Write-Host ""
}

function Invoke-Reject {
    $state = Get-TaskState
    if ($state.State -eq "NONE") {
        Write-Host ""
        Write-Host "No current task found. Nothing to reject."
        Write-Host ""
