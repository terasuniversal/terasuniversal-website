<#
    approval-runner.ps1 - human approval gate and controlled commit
    preparation for the TERAS AI Engineering Orchestrator. Dot-sourced by
    teras-agent.ps1, which must set $RepoRoot, $AiDir, $CurrentTaskPath
    before sourcing this file. Depends on functions from agent-router.ps1
    and qa-runner.ps1 also being sourced first.

    Hard safety invariants enforced in this file, not just documented:
    - staging ever only uses `git add -- <exact paths>`, never `.` or `-A`
    - pre-existing staged changes are detected and block automated commit,
      never unstaged automatically
    - `git commit` only runs after a literal "YES" typed at a live prompt
    - push, deploy, and migration-apply are never invoked anywhere below

    --- Control-plane hardening: external HMAC approval-proof trust root ---

    Production trust root (NEVER auto-generated by this script):
      %LOCALAPPDATA%\TERAS-Hermes-Control\approval-trust\hmac.key.dpapi
    DPAPI CurrentUser-protected. If it is absent, every proof/verification
    operation below fails closed - there is no fallback that invents a key.

    Test isolation: set $env:TERAS_APPROVAL_TRUST_DIR_OVERRIDE to redirect
    Get-ApprovalTrustDir to a disposable scratch directory - this is the
    ONLY supported way to test proof/ledger behavior without ever touching
    the real production trust root or writing into .ai state. Tests call
    New-DisposableApprovalTrustKey explicitly against that overridden path;
    that function structurally refuses to write the literal production
    path even if misused.

    The canonical approval tuple (New-ApprovalCanonicalTuple) binds:
    schema/version, task id, exact worktree path, branch, approved base
    HEAD, allowed files, every runtime/database permission field, the
    exact migration allowlist, a random nonce, and the approval
    timestamp/version. New-ApprovalProof signs that tuple with
    HMAC-SHA256 using the trust-root key ONLY after the human has already
    typed the exact confirmation phrase (teras-agent.ps1's -CreateTask
    flow) - this file never produces a proof on its own initiative.
    db-runner.ps1 is the independent verifier: it recomputes the tuple
    from CURRENT live state/git values (never trusting a cached verdict)
    and re-checks the HMAC; any drift - deliberate tamper or otherwise -
    changes the recomputed tuple and therefore fails the HMAC comparison.

    The external consumption ledger (New-ConsumptionLedgerEntry /
    Consume-ConsumptionLedgerEntry / Set-ConsumptionLedgerLatch), stored
    outside the repository under the same trust-root directory, enforces
    the one-iteration budget and the permanent stop-on-first-failure latch
    independently of anything in .ai/task-state.json. Every ledger
    mutation is atomic (exclusive file handle, in-place rewrite) and
    integrity-bound with its own HMAC over the same trust-root key.
#>

function Get-ApprovalTrustDir {
    if (-not [string]::IsNullOrWhiteSpace($env:TERAS_APPROVAL_TRUST_DIR_OVERRIDE)) {
        return $env:TERAS_APPROVAL_TRUST_DIR_OVERRIDE
    }
    return (Join-Path $env:LOCALAPPDATA "TERAS-Hermes-Control\approval-trust")
}

function Get-ApprovalTrustKeyPath {
    return (Join-Path (Get-ApprovalTrustDir) "hmac.key.dpapi")
}

function Get-ApprovalConsumptionDir {
    return (Join-Path (Get-ApprovalTrustDir) "consumption")
}

# Control-plane hardening repair (HIGH-2): canonical nonce format. This
# orchestrator's own nonce generator (New-ApprovalProof) always produces
# exactly 16 random bytes hex-encoded as 32 lowercase hex characters - the
# same entropy as before, nothing weaker. This is the ONLY nonce shape
# ever accepted anywhere in the trust-root/ledger system: no path
# separators, no dots/traversal, no drive prefixes, no UNC forms, no
# whitespace, no alternate encodings, deterministic (lowercase-only)
# case handling, strictly bounded length. Anything else fails closed
# before it is ever used to build a filesystem path.
$script:NonceFormatPattern = '^[0-9a-f]{32}$'

function Test-NonceFormat {
    param([string]$Nonce)
    if ([string]::IsNullOrEmpty($Nonce)) { return $false }
    return ($Nonce -cmatch $script:NonceFormatPattern)
}

# The ONE canonical helper that may ever turn a Nonce into a consumption
# ledger file path. No caller may build "$Nonce.json" independently -
# New-ConsumptionLedgerEntry, Consume-ConsumptionLedgerEntry, and
# Set-ConsumptionLedgerLatch all route through this function.
#
# Order of operations (matches the repair task's required sequence):
#   1. validate the nonce FORMAT first - before any Join-Path/File I/O
#   2. derive the intended (trust-root) consumption directory
#   3. build the candidate path
#   4. canonicalize both the directory and the candidate with
#      [IO.Path]::GetFullPath (collapses ../, mixed separators, etc.)
#   5. prove the canonicalized candidate is an IMMEDIATE child of the
#      canonicalized consumption directory, with the exact expected
#      file name - defeats traversal, absolute/drive, and UNC escapes
#      even if the format regex above were ever loosened by mistake
#   6. fail closed (return $null) on ANY mismatch - never throws, every
#      caller must treat $null as "deny", never as "no path needed"
function Get-ConsumptionLedgerPathForNonce {
    param([string]$Nonce)

    if (-not (Test-NonceFormat $Nonce)) { return $null }

    $dir = Get-ApprovalConsumptionDir
    if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }

    $canonicalDir = [IO.Path]::GetFullPath($dir).TrimEnd('\', '/')
    $candidate = Join-Path $dir "$Nonce.json"
    $canonicalCandidate = [IO.Path]::GetFullPath($candidate)

    $actualParent = [IO.Path]::GetDirectoryName($canonicalCandidate)
    if ($null -ne $actualParent) { $actualParent = $actualParent.TrimEnd('\', '/') }
    $actualLeaf = [IO.Path]::GetFileName($canonicalCandidate)
    $expectedLeaf = "$Nonce.json"

    if (-not [string]::Equals($actualParent, $canonicalDir, [StringComparison]::OrdinalIgnoreCase)) { return $null }
    if (-not [string]::Equals($actualLeaf, $expectedLeaf, [StringComparison]::Ordinal)) { return $null }

    return $canonicalCandidate
}

# Control-plane hardening repair (MEDIUM-1): schema version bumped from
# "1" to "2" because the canonical approval tuple below now additionally
# binds ConsumptionLedgerPath (previously present on the proof object but
# NOT signed/cross-checked - see New-ApprovalCanonicalTuple and
# Test-ApprovalProofValid in db-runner.ps1). This is a genuine semantic
# change to what is signed, so the version is bumped rather than silently
# reinterpreted; Test-AuthorityProofSchema in db-runner.ps1 already
# compares against this same script variable dynamically, so an old-
# shaped proof signed under version "1" is correctly rejected as
# AUTHORITY_PROOF_SCHEMA_VERSION_UNSUPPORTED rather than silently
# accepted with a field missing from its trust boundary.
$script:ApprovalProofSchemaVersion = "2"

function Protect-ApprovalTrustKeyBytes {
    param([byte[]]$Raw)
    Add-Type -AssemblyName System.Security -ErrorAction SilentlyContinue
    return [System.Security.Cryptography.ProtectedData]::Protect($Raw, $null, [System.Security.Cryptography.DataProtectionScope]::CurrentUser)
}

function Unprotect-ApprovalTrustKeyBytes {
    param([byte[]]$ProtectedBytes)
    Add-Type -AssemblyName System.Security -ErrorAction SilentlyContinue
    return [System.Security.Cryptography.ProtectedData]::Unprotect($ProtectedBytes, $null, [System.Security.Cryptography.DataProtectionScope]::CurrentUser)
}

# Test-only, explicit opt-in key generation. Structurally refuses to ever
# write the literal real production trust-root path, even if a caller
# forgets to set the override - that path may ONLY ever be populated by a
# human/operator outside this orchestrator (section 2 of the hardening
# task: "NEVER auto-generate the real production key").
function New-DisposableApprovalTrustKey {
    param([Parameter(Mandatory = $true)][string]$Path)

    $realProdPath = (Join-Path $env:LOCALAPPDATA "TERAS-Hermes-Control\approval-trust\hmac.key.dpapi").TrimEnd('\')
    if ([string]::Equals($Path.TrimEnd('\'), $realProdPath, [StringComparison]::OrdinalIgnoreCase)) {
        throw "REFUSED: New-DisposableApprovalTrustKey must never write the real production trust-root path ($realProdPath). Use an isolated test/scratch path via `$env:TERAS_APPROVAL_TRUST_DIR_OVERRIDE."
    }

    $dir = Split-Path -Parent $Path
    if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
    $raw = New-Object byte[] 32
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($raw)
    $protectedBytes = Protect-ApprovalTrustKeyBytes -Raw $raw
    [IO.File]::WriteAllBytes($Path, $protectedBytes)
}

# Fail-closed read: a missing, unreadable, or undecryptable key returns
# $null - every caller must treat $null as "no trust root; deny", never as
# "trust root not required."
function Get-ApprovalTrustKeyBytes {
    param([string]$Path)
    if ([string]::IsNullOrWhiteSpace($Path) -or -not (Test-Path -LiteralPath $Path -PathType Leaf)) {
        return $null
    }
    try {
        $protectedBytes = [IO.File]::ReadAllBytes($Path)
        return (Unprotect-ApprovalTrustKeyBytes -ProtectedBytes $protectedBytes)
    } catch {
        return $null
    }
}

function Get-HmacSha256Hex {
    param([byte[]]$KeyBytes, [string]$Message)
    $hmacAlg = New-Object System.Security.Cryptography.HMACSHA256(, $KeyBytes)
    try {
        $bytes = $hmacAlg.ComputeHash([System.Text.Encoding]::UTF8.GetBytes($Message))
        return -join ($bytes | ForEach-Object { $_.ToString("x2") })
    } finally {
        $hmacAlg.Dispose()
    }
}

# Constant-time comparison - avoids leaking a timing side-channel on the
# HMAC/integrity comparisons below. Matches the stated threat model
# (accidental/manual tampering defense, not a hardened crypto library) but
# costs nothing to include correctly.
function Test-ConstantTimeStringEqual {
    param([string]$A, [string]$B)
    if ($null -eq $A -or $null -eq $B) { return $false }
    if ($A.Length -ne $B.Length) { return $false }
    $diff = 0
    for ($i = 0; $i -lt $A.Length; $i++) { $diff = $diff -bor ([int][char]$A[$i] -bxor [int][char]$B[$i]) }
    return ($diff -eq 0)
}

# The canonical approval tuple - the exact set of fields the HMAC proof
# signs. Deliberately built as an [ordered] hashtable (never a hashtable
# literal or a PSCustomObject built via loose property assignment) so
# ConvertTo-Json's key order - and therefore the exact bytes signed - is
# fully deterministic given the same inputs. Any caller that wants a valid
# proof MUST reconstruct this tuple the same way db-runner.ps1 does for
# verification; the two are never allowed to diverge in field set or order.
function New-ApprovalCanonicalTuple {
    param(
        $State,
        [string]$WorktreePath,
        [string]$Branch,
        [string]$BaseHeadSha,
        [string]$Nonce,
        [string]$ApprovedAtUtc,
        [string]$ConsumptionLedgerPath
    )

    return [ordered]@{
        SchemaVersion = $script:ApprovalProofSchemaVersion
        TaskId        = [string]$State.TaskId
        WorktreePath  = $WorktreePath
        Branch        = $Branch
        BaseHeadSha   = $BaseHeadSha
        AllowedFiles  = @(@($State.AllowedFiles) | Sort-Object)
        Permissions   = [ordered]@{
            LocalDisposableDatabaseAllowed  = [bool]$State.LocalDisposableDatabaseAllowed
            LocalMigrationValidationAllowed = [bool]$State.LocalMigrationValidationAllowed
            DockerIterationsAllowed         = [int]$State.DockerIterationsAllowed
            StopOnFirstFailure              = [bool]$State.StopOnFirstFailure
            SyntheticDataOnly               = [bool]$State.SyntheticDataOnly
            RemoteDbAllowed                 = [bool]$State.RemoteDbAllowed
            StagingAllowed                  = [bool]$State.StagingAllowed
            ProductionAllowed               = [bool]$State.ProductionAllowed
            PublishedPortsAllowed           = [bool]$State.PublishedPortsAllowed
            PersistentDbVolumeAllowed       = [bool]$State.PersistentDbVolumeAllowed
            SourceEditAllowedDuringRuntime  = [bool]$State.SourceEditAllowedDuringRuntime
            PushAllowed                     = [bool]$State.PushAllowed
            MergeAllowed                    = [bool]$State.MergeAllowed
            DeployAllowed                   = [bool]$State.DeployAllowed
        }
        MigrationAllowlist = @(@($State.LocalMigrationAllowlist) | Sort-Object)
        Nonce              = $Nonce
        ApprovedAtUtc      = $ApprovedAtUtc
        ApprovalVersion    = 1
        # Control-plane hardening repair (MEDIUM-1): now part of the signed
        # tuple (schema version 2+), using the SAME canonicalized value
        # Get-ConsumptionLedgerPathForNonce derives from the nonce - never
        # an independently-typed "$Nonce.json" string. Any drift between
        # the proof's claimed ledger path and the one actually derived
        # from the (now-authenticated) nonce changes the recomputed tuple
        # bytes and fails the HMAC comparison in db-runner.ps1.
        ConsumptionLedgerPath = $ConsumptionLedgerPath
    }
}

function Get-ApprovalCanonicalTupleJson {
    param($Tuple)
    return ($Tuple | ConvertTo-Json -Depth 10 -Compress)
}

# Produces a signed approval proof. Must only ever be called AFTER the
# human has already typed the exact confirmation phrase - this function
# itself performs no human-approval gating, it only signs what the caller
# (teras-agent.ps1 -CreateTask) already confirmed. Fails closed (Success =
# $false) whenever the trust root is missing/unreadable or git metadata is
# unavailable - never falls back to an unsigned or self-asserted proof.
function New-ApprovalProof {
    param($State, [string]$RepoRoot)

    $keyBytes = Get-ApprovalTrustKeyBytes -Path (Get-ApprovalTrustKeyPath)
    if ($null -eq $keyBytes) {
        return [pscustomobject]@{ Success = $false; Reason = "TRUST_ROOT_KEY_MISSING_OR_UNREADABLE"; Proof = $null }
    }

    Push-Location $RepoRoot
    try {
        $branch = (git rev-parse --abbrev-ref HEAD 2>$null | Out-String).Trim()
        $headSha = (git rev-parse HEAD 2>$null | Out-String).Trim()
    } catch {
        return [pscustomobject]@{ Success = $false; Reason = "GIT_METADATA_UNAVAILABLE"; Proof = $null }
    } finally {
        Pop-Location
    }
    if ([string]::IsNullOrWhiteSpace($branch) -or $headSha -notmatch '^[0-9a-f]{40}$') {
        return [pscustomobject]@{ Success = $false; Reason = "GIT_METADATA_MALFORMED"; Proof = $null }
    }

    $worktreePath = (Resolve-Path -LiteralPath $RepoRoot).Path
    # 16 random bytes -> 32 lowercase hex chars - matches $script:NonceFormatPattern
    # exactly (Test-NonceFormat), same entropy as before the repair.
    $nonceBytes = New-Object byte[] 16
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($nonceBytes)
    $nonce = -join ($nonceBytes | ForEach-Object { $_.ToString("x2") })
    if (-not (Test-NonceFormat $nonce)) {
        # Structurally unreachable given the generator above, but this is
        # the trust boundary - never proceed on an assumption.
        return [pscustomobject]@{ Success = $false; Reason = "NONCE_GENERATION_INVARIANT_VIOLATED"; Proof = $null }
    }
    $approvedAtUtc = (Get-Date).ToUniversalTime().ToString("yyyy-MM-ddTHH:mm:ss.fffZ")

    # Control-plane hardening repair (HIGH-2): derive the ledger path from
    # the (self-generated, already-validated) nonce through the ONE
    # canonical helper before it is ever used in a tuple, signature, or
    # ledger write - never an ad hoc "$nonce.json" string.
    $ledgerPath = Get-ConsumptionLedgerPathForNonce -Nonce $nonce
    if ($null -eq $ledgerPath) {
        return [pscustomobject]@{ Success = $false; Reason = "LEDGER_PATH_DERIVATION_FAILED"; Proof = $null }
    }

    $tuple = New-ApprovalCanonicalTuple -State $State -WorktreePath $worktreePath -Branch $branch -BaseHeadSha $headSha -Nonce $nonce -ApprovedAtUtc $approvedAtUtc -ConsumptionLedgerPath $ledgerPath
    $canonicalJson = Get-ApprovalCanonicalTupleJson -Tuple $tuple
    $hmac = Get-HmacSha256Hex -KeyBytes $keyBytes -Message $canonicalJson

    $ledgerResult = New-ConsumptionLedgerEntry -Nonce $nonce -TaskId $State.TaskId -KeyBytes $keyBytes
    if (-not $ledgerResult.Success) {
        return [pscustomobject]@{ Success = $false; Reason = "CONSUMPTION_LEDGER_CREATE_FAILED: $($ledgerResult.Reason)"; Proof = $null }
    }

    $proof = [pscustomobject]@{
        SchemaVersion         = $script:ApprovalProofSchemaVersion
        Nonce                 = $nonce
        ApprovedAtUtc         = $approvedAtUtc
        WorktreePath          = $worktreePath
        Branch                = $branch
        BaseHeadSha           = $headSha
        Hmac                  = $hmac
        ConsumptionLedgerPath = $ledgerResult.Path
    }
    return [pscustomobject]@{ Success = $true; Reason = "OK"; Proof = $proof }
}

# ---------------------------------------------------------------------------
# External consumption ledger - one file per nonce, stored OUTSIDE the
# repository under the trust-root directory. Enforces the one-iteration
# budget and the permanent stop-on-first-failure latch independently of
# .ai/task-state.json. Every mutation holds an exclusive file handle
# (FileShare.None) for the whole read-modify-write, so a concurrent
# attempt fails closed rather than racing.
# ---------------------------------------------------------------------------

$script:ConsumptionLedgerFieldOrder = @("Nonce", "TaskId", "IssuedAtUtc", "MaxIterations", "ConsumedIterations", "Latched", "LatchReason")

function Get-ConsumptionLedgerIntegrityPayload {
    param($Entry)
    $ordered = [ordered]@{}
    foreach ($f in $script:ConsumptionLedgerFieldOrder) { $ordered[$f] = $Entry.$f }
    return ($ordered | ConvertTo-Json -Compress -Depth 5)
}

# Atomic, exclusive-create: a second attempt to create a ledger entry for
# the same nonce (e.g. a replayed/duplicated proof) fails outright rather
# than overwriting the original budget state.
function New-ConsumptionLedgerEntry {
    param([string]$Nonce, [string]$TaskId, [byte[]]$KeyBytes)

    # HIGH-2 repair: nonce format + path containment validated via the
    # ONE canonical helper BEFORE any Join-Path/file I/O below. No ad hoc
    # "$Nonce.json" string construction anywhere in this function.
    $path = Get-ConsumptionLedgerPathForNonce -Nonce $Nonce
    if ($null -eq $path) {
        return [pscustomobject]@{ Success = $false; Reason = "NONCE_FORMAT_INVALID_OR_PATH_ESCAPE"; Path = $null }
    }
    if (Test-Path -LiteralPath $path) {
        return [pscustomobject]@{ Success = $false; Reason = "NONCE_ALREADY_HAS_LEDGER_ENTRY"; Path = $path }
    }

    $entry = [pscustomobject]@{
        Nonce               = $Nonce
        TaskId              = $TaskId
        IssuedAtUtc         = (Get-Date).ToUniversalTime().ToString("yyyy-MM-ddTHH:mm:ss.fffZ")
        MaxIterations       = 1
        ConsumedIterations  = 0
        Latched             = $false
        LatchReason         = $null
    }
    $integrity = Get-HmacSha256Hex -KeyBytes $KeyBytes -Message (Get-ConsumptionLedgerIntegrityPayload -Entry $entry)
    $entry | Add-Member -MemberType NoteProperty -Name Integrity -Value $integrity

    $tmp = "$path.tmp.$([Guid]::NewGuid().ToString('N'))"
    try {
        $fs = [IO.File]::Open($tmp, [IO.FileMode]::CreateNew, [IO.FileAccess]::Write, [IO.FileShare]::None)
        try {
            $bytes = [System.Text.Encoding]::UTF8.GetBytes(($entry | ConvertTo-Json -Depth 5))
            $fs.Write($bytes, 0, $bytes.Length)
        } finally {
            $fs.Dispose()
        }
        [IO.File]::Move($tmp, $path)
    } catch {
        if (Test-Path -LiteralPath $tmp) { Remove-Item -LiteralPath $tmp -Force -ErrorAction SilentlyContinue }
        return [pscustomobject]@{ Success = $false; Reason = "LEDGER_WRITE_FAILED: $($_.Exception.Message)"; Path = $path }
    }
    return [pscustomobject]@{ Success = $true; Reason = "OK"; Path = $path }
}

# Strict-schema + integrity check for a ledger file - exactly the 7 content
# fields plus Integrity, nothing more, nothing less; any mismatch fails
# closed. Read-only; never mutates the file.
# Strict-schema + integrity check performed directly against an
# already-parsed ledger entry object (no file I/O) - the core logic
# shared by both the read-only Test-ConsumptionLedgerIntegrity (which
# opens the file itself) and Consume-ConsumptionLedgerEntry /
# Set-ConsumptionLedgerLatch (which already hold the file open under an
# exclusive lock and must never re-open it, or the re-open would
# deadlock/fail against their own lock).
function Test-ConsumptionLedgerEntryIntegrity {
    param($Entry, [byte[]]$KeyBytes)

    if ($null -eq $Entry) {
        return [pscustomobject]@{ Valid = $false; Reason = "LEDGER_FILE_MALFORMED" }
    }
    if ($null -eq $KeyBytes) {
        return [pscustomobject]@{ Valid = $false; Reason = "TRUST_ROOT_KEY_MISSING_OR_UNREADABLE" }
    }

    $actualNames = @($Entry.PSObject.Properties.Name)
    $expected = @($script:ConsumptionLedgerFieldOrder + @("Integrity"))
    $missing = @($expected | Where-Object { $_ -notin $actualNames })
    $unknown = @($actualNames | Where-Object { $_ -notin $expected })
    if ($missing.Count -gt 0) {
        return [pscustomobject]@{ Valid = $false; Reason = "LEDGER_SCHEMA_MISSING_FIELDS: $($missing -join ', ')" }
    }
    if ($unknown.Count -gt 0) {
        return [pscustomobject]@{ Valid = $false; Reason = "LEDGER_SCHEMA_UNKNOWN_FIELDS: $($unknown -join ', ')" }
    }

    $expectedHmac = Get-HmacSha256Hex -KeyBytes $KeyBytes -Message (Get-ConsumptionLedgerIntegrityPayload -Entry $Entry)
    if (-not (Test-ConstantTimeStringEqual -A $expectedHmac -B ([string]$Entry.Integrity))) {
        return [pscustomobject]@{ Valid = $false; Reason = "LEDGER_INTEGRITY_TAMPER_DETECTED" }
    }
    return [pscustomobject]@{ Valid = $true; Reason = "OK" }
}

# Read-only, file-opening variant for external callers (tests, status
# checks) that do not already hold the file open. Never used internally
# by Consume-ConsumptionLedgerEntry/Set-ConsumptionLedgerLatch - see
# Test-ConsumptionLedgerEntryIntegrity above for why.
function Test-ConsumptionLedgerIntegrity {
    param([string]$Path, [byte[]]$KeyBytes)

    if ([string]::IsNullOrWhiteSpace($Path) -or -not (Test-Path -LiteralPath $Path -PathType Leaf)) {
        return [pscustomobject]@{ Valid = $false; Reason = "LEDGER_FILE_MISSING"; Entry = $null }
    }
    if ($null -eq $KeyBytes) {
        return [pscustomobject]@{ Valid = $false; Reason = "TRUST_ROOT_KEY_MISSING_OR_UNREADABLE"; Entry = $null }
    }
    try {
        $entry = Get-Content -LiteralPath $Path -Raw | ConvertFrom-Json
    } catch {
        return [pscustomobject]@{ Valid = $false; Reason = "LEDGER_FILE_MALFORMED"; Entry = $null }
    }

    $check = Test-ConsumptionLedgerEntryIntegrity -Entry $entry -KeyBytes $KeyBytes
    if (-not $check.Valid) {
        return [pscustomobject]@{ Valid = $false; Reason = $check.Reason; Entry = $null }
    }
    return [pscustomobject]@{ Valid = $true; Reason = "OK"; Entry = $entry }
}

# Consumes exactly one iteration, in place, under an exclusive file lock.
# Must be called BEFORE bounded local runtime starts (never after). Fails
# closed on: missing trust root, missing/corrupt ledger, a permanent latch
# from a prior first failure, an already-exhausted budget (replay), or
# lock contention (a concurrent consumer).
function Consume-ConsumptionLedgerEntry {
    param([string]$Nonce)

    $path = Join-Path (Get-ApprovalConsumptionDir) "$Nonce.json"
    $keyBytes = Get-ApprovalTrustKeyBytes -Path (Get-ApprovalTrustKeyPath)
    if ($null -eq $keyBytes) {
        return [pscustomobject]@{ Success = $false; Reason = "TRUST_ROOT_KEY_MISSING_OR_UNREADABLE" }
    }
    if (-not (Test-Path -LiteralPath $path -PathType Leaf)) {
        return [pscustomobject]@{ Success = $false; Reason = "LEDGER_FILE_MISSING" }
    }

    try {
        $fs = [IO.File]::Open($path, [IO.FileMode]::Open, [IO.FileAccess]::ReadWrite, [IO.FileShare]::None)
    } catch {
        return [pscustomobject]@{ Success = $false; Reason = "LEDGER_LOCK_CONTENDED_OR_UNAVAILABLE" }
    }
    try {
        $reader = New-Object IO.StreamReader($fs)
        $raw = $reader.ReadToEnd()
        try { $entry = $raw | ConvertFrom-Json } catch { return [pscustomobject]@{ Success = $false; Reason = "LEDGER_FILE_MALFORMED" } }

        $integrityCheck = Test-ConsumptionLedgerEntryIntegrity -Entry $entry -KeyBytes $keyBytes
        if (-not $integrityCheck.Valid) {
            return [pscustomobject]@{ Success = $false; Reason = $integrityCheck.Reason }
        }
        if ($entry.Latched) {
            return [pscustomobject]@{ Success = $false; Reason = "LATCHED_BY_FIRST_FAILURE" }
        }
        if ([int]$entry.ConsumedIterations -ge [int]$entry.MaxIterations) {
            return [pscustomobject]@{ Success = $false; Reason = "CONSUMPTION_BUDGET_ALREADY_EXHAUSTED" }
        }

        $entry.ConsumedIterations = [int]$entry.ConsumedIterations + 1
        $entry.PSObject.Properties.Remove("Integrity")
        $newIntegrity = Get-HmacSha256Hex -KeyBytes $keyBytes -Message (Get-ConsumptionLedgerIntegrityPayload -Entry $entry)
        $entry | Add-Member -MemberType NoteProperty -Name Integrity -Value $newIntegrity

        $bytes = [System.Text.Encoding]::UTF8.GetBytes(($entry | ConvertTo-Json -Depth 5))
        $fs.SetLength(0)
        $fs.Seek(0, [IO.SeekOrigin]::Begin) | Out-Null
        $fs.Write($bytes, 0, $bytes.Length)
        $fs.Flush()
        return [pscustomobject]@{ Success = $true; Reason = "OK" }
    } finally {
        $fs.Dispose()
    }
}

# Permanently latches a ledger entry after ANY runtime precondition or
# execution failure - section 10's "first failure permanently latches that
# authorization." Idempotent: latching an already-latched entry is a no-op
# success. Once latched, Consume-ConsumptionLedgerEntry and
# Test-ApprovalProofValid both fail closed forever for that nonce,
# regardless of remaining budget.
function Set-ConsumptionLedgerLatch {
    param([string]$Nonce, [string]$Reason)

    $path = Join-Path (Get-ApprovalConsumptionDir) "$Nonce.json"
    $keyBytes = Get-ApprovalTrustKeyBytes -Path (Get-ApprovalTrustKeyPath)
    if ($null -eq $keyBytes -or -not (Test-Path -LiteralPath $path -PathType Leaf)) { return $false }

    try {
        $fs = [IO.File]::Open($path, [IO.FileMode]::Open, [IO.FileAccess]::ReadWrite, [IO.FileShare]::None)
    } catch {
        return $false
    }
    try {
        $reader = New-Object IO.StreamReader($fs)
        try { $entry = ($reader.ReadToEnd()) | ConvertFrom-Json } catch { return $false }

        $entry.Latched = $true
        $entry.LatchReason = $Reason
        $entry.PSObject.Properties.Remove("Integrity")
        $newIntegrity = Get-HmacSha256Hex -KeyBytes $keyBytes -Message (Get-ConsumptionLedgerIntegrityPayload -Entry $entry)
        $entry | Add-Member -MemberType NoteProperty -Name Integrity -Value $newIntegrity

        $bytes = [System.Text.Encoding]::UTF8.GetBytes(($entry | ConvertTo-Json -Depth 5))
        $fs.SetLength(0)
        $fs.Seek(0, [IO.SeekOrigin]::Begin) | Out-Null
        $fs.Write($bytes, 0, $bytes.Length)
        $fs.Flush()
        return $true
    } finally {
        $fs.Dispose()
    }
}

function Get-CommitMessage {
    param($State)

    $desc = $State.Description.Trim()
    $prefix = "fix"
    $rest = $desc

    if ($desc -match '(?i)^(fix|correct|resolve|repair|refine|patch|harden)\b\s*(.*)$') {
        $prefix = "fix"; $rest = $Matches[2]
    } elseif ($desc -match '(?i)^(add|create|implement|introduce|build)\b\s*(.*)$') {
        $prefix = "feat"; $rest = $Matches[2]
    } elseif ($desc -match '(?i)^(refactor)\b\s*(.*)$') {
        $prefix = "refactor"; $rest = $Matches[2]
    } elseif ($desc -match '(?i)^(document|docs)\b\s*(.*)$') {
        $prefix = "docs"; $rest = $Matches[2]
    } elseif ($desc -match '(?i)^(test)\b\s*(.*)$') {
        $prefix = "test"; $rest = $Matches[2]
    } elseif ($State.Category -eq "Feature") {
        $prefix = "feat"; $rest = $desc
    }

    $rest = $rest.Trim()
    if ($rest.Length -eq 0) { $rest = $desc }
    $rest = $rest.Substring(0, 1).ToLowerInvariant() + $rest.Substring(1)
    $rest = $rest.TrimEnd('.')

    return "$prefix`: $rest"
}

